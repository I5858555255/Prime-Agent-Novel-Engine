def test_dialogue_ending_with_ascii_or_cjk_quote_is_closed():
    target = 2500  # length floor 1000
    t1 = _filler() + '陈老根沉声道："这孩子，我带走了。"'
    passed, issues = validate_scene_text(t1, target)
    assert passed, issues
    t2 = _filler() + "陈老根沉声道：“这孩子，我带走了。”"
    passed2, issues2 = validate_scene_text(t2, target)
    assert passed2, issues2


def test_emdash_dangling_ending_still_truncated():
    t = _filler() + "他伸出手，想要抓住那一线光——"
    passed, issues = validate_scene_text(t, 2500)
    assert not passed
    assert any("truncated_or_no_sentence_ending" in i for i in issues)
